import type { Hex, SyntaxColors, TokenColor } from "../types.ts";

const token = (
  scope: string | string[],
  foreground: Hex,
  fontStyle?: string,
): TokenColor => ({
  scope,
  settings: {
    foreground,
    ...(fontStyle ? { fontStyle } : {}),
  },
});

